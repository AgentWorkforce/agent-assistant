import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { HumanEvalCase } from './human-suite.js';

export interface ParseHumanEvalMarkdownOptions {
  suite: string;
  sourcePath?: string;
}

export interface CompileHumanEvalSuitesOptions {
  suitesDir: string;
  suite?: string;
  generatedHeader?: string;
}

export interface CompiledHumanEvalSuite {
  suite: string;
  sourcePath: string;
  outputPath: string;
  cases: HumanEvalCase[];
}

export interface CompileHumanEvalSuitesResult {
  total: number;
  suites: CompiledHumanEvalSuite[];
}

const DEFAULT_GENERATED_HEADER = [
  '# Generated from cases.md.',
  '# Do not edit this file directly; edit cases.md in this suite instead.',
].join('\n');

interface CaseBlock {
  id: string;
  lines: string[];
}

type MarkdownSections = Record<string, string[]>;

export function compileHumanEvalSuitesFromMarkdown(
  options: CompileHumanEvalSuitesOptions,
): CompileHumanEvalSuitesResult {
  const suites = options.suite ? [options.suite] : readdirSync(options.suitesDir).sort(compareStrings);
  const compiled: CompiledHumanEvalSuite[] = [];
  let total = 0;

  for (const suite of suites) {
    const suiteDir = path.join(options.suitesDir, suite);
    const sourcePath = path.join(suiteDir, 'cases.md');
    const outputPath = path.join(suiteDir, 'cases.jsonl');

    if (!existsSync(sourcePath)) {
      if (options.suite) throw new Error(`No cases.md found for suite "${suite}"`);
      continue;
    }

    const cases = parseHumanEvalCasesMarkdown(readFileSync(sourcePath, 'utf8'), {
      suite,
      sourcePath,
    });
    const output = [
      options.generatedHeader ?? DEFAULT_GENERATED_HEADER,
      ...cases.map((evalCase) => JSON.stringify(evalCase)),
    ].join('\n');

    writeFileSync(outputPath, `${output}\n`);
    compiled.push({ suite, sourcePath, outputPath, cases });
    total += cases.length;
  }

  return { total, suites: compiled };
}

export function parseHumanEvalCasesMarkdown(
  markdown: string,
  options: ParseHumanEvalMarkdownOptions,
): HumanEvalCase[] {
  return splitCaseBlocks(markdown).map((block) => parseCaseBlock(block, options));
}

function splitCaseBlocks(markdown: string): CaseBlock[] {
  const lines = markdown.split('\n');
  const blocks: CaseBlock[] = [];
  let current: CaseBlock | null = null;
  let inFence = false;

  for (const line of lines) {
    if (/^```/.test(line.trim())) {
      inFence = !inFence;
      if (current) current.lines.push(line);
      continue;
    }
    if (inFence) {
      if (current) current.lines.push(line);
      continue;
    }

    const match = /^##\s+([A-Za-z0-9_.:-]+)\s*$/.exec(line.trim());
    if (match) {
      if (current) blocks.push(current);
      current = { id: match[1] ?? '', lines: [] };
      continue;
    }
    if (current) current.lines.push(line);
  }

  if (current) blocks.push(current);
  return blocks;
}

function parseCaseBlock(block: CaseBlock, options: ParseHumanEvalMarkdownOptions): HumanEvalCase {
  const sections = splitSections(block.lines);
  const meta = parseMetadata(sections.meta ?? []);
  const deterministic = parseKeyValueSection(sections['Deterministic Checks'] ?? []);
  const mock = parseKeyValueSection(sections.Mock ?? []);
  const expected: Record<string, unknown> = { ...deterministic };
  const humanMust = parseBullets([...(sections.Must ?? []), ...(sections['Human Must'] ?? [])]);
  const humanMustNot = parseBullets([
    ...(sections['Must Not'] ?? []),
    ...(sections['Human Must Not'] ?? []),
  ]);

  if (humanMust.length > 0) expected.must = humanMust;
  if (humanMustNot.length > 0) expected.mustNot = humanMustNot;
  if (meta.humanReview !== undefined) expected.humanReviewRequired = meta.humanReview;
  if (deterministic.humanReviewRequired !== undefined) {
    expected.humanReviewRequired = deterministic.humanReviewRequired;
  }

  const input: Record<string, unknown> = {};
  const message = sectionText(sections.Message);
  if (message.length > 0) input.message = message;
  const systemPrompt = sectionText(sections['System Prompt Override'] ?? sections['System Prompt']);
  if (systemPrompt.length > 0) input.systemPrompt = systemPrompt;
  const actualPath = sectionText(sections['Actual Path']);
  if (actualPath.length > 0) input.actualPath = actualPath;
  const candidateOutput = sectionText(sections['Candidate Output']);
  if (candidateOutput.length > 0) input.candidateOutput = candidateOutput;
  const candidateOutputPath = sectionText(sections['Candidate Output Path']);
  if (candidateOutputPath.length > 0) input.candidateOutputPath = candidateOutputPath;
  const threadHistory = parseThreadHistory(sections['Thread History'] ?? []);
  if (threadHistory.length > 0) input.threadHistory = threadHistory;

  if (!input.message && !input.actualPath) {
    const source = options.sourcePath ?? 'cases.md';
    throw new Error(`${source}: case ${block.id} needs a ### Message or ### Actual Path section`);
  }

  const evalCase: HumanEvalCase = {
    id: block.id,
    suite: stringValue(meta.suite) ?? options.suite,
    executor: stringValue(meta.executor) ?? 'manual',
    kind: stringValue(meta.kind) ?? 'capability',
    input,
    expected,
    tags: Array.isArray(meta.tags) ? meta.tags.map(String) : [],
  };

  if (typeof meta.trials === 'number' && Number.isFinite(meta.trials)) evalCase.trials = meta.trials;
  if (Object.keys(mock).length > 0) evalCase.mock = mock;

  return evalCase;
}

function splitSections(lines: string[]): MarkdownSections {
  const sections: MarkdownSections = { meta: [] };
  let current = 'meta';

  for (const line of lines) {
    const match = /^###\s+(.+?)\s*$/.exec(line.trim());
    if (match) {
      current = match[1] ?? '';
      sections[current] = [];
      continue;
    }
    sections[current]?.push(line);
  }

  return sections;
}

function parseMetadata(lines: string[]): Record<string, unknown> {
  const values: Record<string, unknown> = {};
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const match = /^([A-Za-z][A-Za-z ]*):\s*(.*)$/.exec(trimmed);
    if (!match) continue;
    const rawKey = match[1] ?? '';
    const rawValue = match[2] ?? '';
    const key = normalizeKey(rawKey);
    const value = parseScalar(rawValue);
    if (key === 'tags') values.tags = splitCommaList(rawValue);
    else if (key === 'trials') values.trials = Number(value);
    else if (key === 'humanReview') values.humanReview = Boolean(value);
    else values[key] = value;
  }
  return values;
}

function parseKeyValueSection(lines: string[]): Record<string, unknown> {
  const values: Record<string, unknown> = {};
  let currentKey: string | null = null;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    const bullet = /^-\s+(.*)$/.exec(trimmed);
    if (bullet && currentKey) {
      const current = values[currentKey];
      if (!Array.isArray(current)) values[currentKey] = [];
      (values[currentKey] as unknown[]).push(parseScalar(bullet[1] ?? ''));
      continue;
    }

    const match = /^([A-Za-z][A-Za-z0-9 ]*):\s*(.*)$/.exec(trimmed);
    if (!match) continue;
    const key = normalizeKey(match[1] ?? '');
    const rawValue = match[2] ?? '';
    if (rawValue.trim().length === 0) {
      values[key] = [];
      currentKey = key;
    } else {
      const value = arrayKeys().has(key) ? splitCommaList(rawValue) : parseScalar(rawValue);
      values[key] = value;
      currentKey = key;
    }
  }

  return values;
}

function parseBullets(lines: string[]): string[] {
  return lines
    .map((line) => /^-\s+(.*)$/.exec(line.trim())?.[1] ?? '')
    .map((line) => line.trim())
    .filter(Boolean);
}

function sectionText(lines: string[] | undefined): string {
  return (lines ?? []).join('\n').trim();
}

function parseThreadHistory(lines: string[]): Array<{ role: 'user' | 'assistant'; content: string }> {
  const history: Array<{ role: 'user' | 'assistant'; content: string }> = [];
  for (const line of lines) {
    const match = /^-\s*(user|assistant):\s*(.*)$/i.exec(line.trim());
    if (!match) continue;
    const role = (match[1] ?? '').toLowerCase() as 'user' | 'assistant';
    history.push({ role, content: match[2] ?? '' });
  }
  return history;
}

function normalizeKey(key: string): string {
  return key
    .trim()
    .replace(/\s+([a-zA-Z0-9])/g, (_, char: string) => char.toUpperCase())
    .replace(/^[A-Z]/, (char) => char.toLowerCase());
}

function parseScalar(raw: string): unknown {
  const value = raw.trim();
  if (/^(true|false)$/i.test(value)) return value.toLowerCase() === 'true';
  if (/^-?\d+(?:\.\d+)?$/.test(value)) return Number(value);
  return value;
}

function splitCommaList(raw: string): string[] {
  return raw
    .split(',')
    .map((item) => item.trim())
    .filter(Boolean);
}

function arrayKeys(): Set<string> {
  return new Set([
    'contentIncludes',
    'contentMatches',
    'forbidPhrases',
    'forbidPatterns',
    'toolCallsInclude',
    'toolCallsExclude',
  ]);
}

function compareStrings(left: string, right: string): number {
  return left.localeCompare(right, 'en');
}

function stringValue(value: unknown): string | undefined {
  return typeof value === 'string' && value.length > 0 ? value : undefined;
}
